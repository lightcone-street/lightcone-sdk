describe("local trade rejections", () => {
  it("match orders multi rejects invalid trades", () => {
    const valid = clientMatchParams();
    const build = (params: MatchOrdersMultiParams) => () =>
      buildMatchOrdersMultiIx(params, inputs.programId);

    assert.throws(
      build({ ...valid, makerOrders: [] }),
      programError("MissingField", (error) => /maker_orders/.test(error.message)),
    );
    assert.throws(
      build({ ...valid, makerOrders: Array(MAX_MAKERS + 1).fill(valid.makerOrders[1]) }),
      programError("TooManyMakers", (error) => /12/.test(error.message)),
    );
    assert.throws(
      build({ ...valid, makerFillAmounts: [100n] }),
      programError("MissingField", (error) => /maker_fill_amounts/.test(error.message)),
    );
    assert.throws(
      build({ ...valid, takerFillAmounts: [60n, 60n, 60n] }),
      programError("MissingField", (error) => /taker_fill_amounts/.test(error.message)),
    );

    // A participant signed for another pair or market.
    assert.throws(
      build({
        ...valid,
        makerOrders: [
          valid.makerOrders[0],
          { ...valid.makerOrders[1], quoteMint: mint(inputs.collateralB, 1) },
        ],
      }),
      programError("InvalidOrderbook"),
    );
    assert.throws(
      build({
        ...valid,
        takerOrder: { ...valid.takerOrder, market: new PublicKey(Buffer.alloc(32, 0x4e)) },
      }),
      programError("InvalidOrderbook"),
    );

    // A maker on the taker's side.
    assert.throws(
      build({
        ...valid,
        makerOrders: [{ ...valid.makerOrders[0], side: OrderSide.BID }, valid.makerOrders[1]],
      }),
      programError("InvalidSide", (error) => /: 0$/.test(error.message)),
    );

    // Mask bits beyond the two makers; the taker bit alone stays valid.
    for (const mask of [0x0004, 0x4000, 0x8004]) {
      assert.throws(build({ ...valid, fullFillBitmask: mask }), programError("Serialization"));
    }
    assert.doesNotThrow(build({ ...valid, fullFillBitmask: 0x8003 }));

    assert.throws(
      build({ ...valid, quoteDepositMint: valid.baseDepositMint }),
      programError("DepositMintMismatch"),
    );
  });

  it("deposit and swap rejects invalid trades", () => {
    const valid = clientDepositAndSwapParams();
    const [maker] = valid.makers;
    const build = (params: DepositAndSwapParams) => () =>
      buildDepositAndSwapIx(params, inputs.programId);

    assert.throws(
      build({ ...valid, makers: [] }),
      programError("MissingField", (error) => /makers/.test(error.message)),
    );
    assert.throws(
      build({ ...valid, makers: Array(MAX_MAKERS + 1).fill(maker) }),
      programError("TooManyMakers", (error) => /12/.test(error.message)),
    );
    for (const numOutcomes of [1, 7]) {
      assert.throws(build({ ...valid, numOutcomes }), programError("InvalidOutcomeCount"));
    }

    // A maker signed for another pair.
    assert.throws(
      build({
        ...valid,
        makers: [{ ...maker, order: { ...maker.order, baseMint: mint(inputs.collateralA, 0) } }],
      }),
      programError("InvalidOrderbook"),
    );

    // A maker on the taker's side.
    assert.throws(
      build({ ...valid, makers: [{ ...maker, order: { ...maker.order, side: OrderSide.ASK } }] }),
      programError("InvalidSide", (error) => /: 1$/.test(error.message)),
    );

    assert.throws(
      build({ ...valid, quoteDepositMint: valid.baseDepositMint }),
      programError("DepositMintMismatch"),
    );

    // Depositors must split the collateral behind the asset their order gives:
    // base collateral for the SELL taker, quote for the BUY maker.
    assert.throws(
      build({ ...valid, takerDepositMint: inputs.collateralB }),
      programError("DepositMintMismatch"),
    );
    assert.throws(
      build({ ...valid, makers: [{ ...maker, depositMint: inputs.collateralA }] }),
      programError("DepositMintMismatch"),
    );

    // A non-depositing participant's deposit mint is not encoded or checked.
    assert.doesNotThrow(
      build({ ...valid, makers: [{ ...maker, isDeposit: false, depositMint: PublicKey.default }] }),
    );
  });
});
